// Sound design cues (seconds) — generated by tools/sfx.sh.
const WHOOSH = [3.9, 9.4, 12.6, 14.9, 22.0, 31.5, 35.2, 43.4, 45.3, 48.3, 53.0, 64.2, 69.4];
const HIT = [2.6, 8.1, 18.3, 30.1, 46.7, 63.0, 68.8];

const PyryRing: React.FC<{t: number}> = ({t}) => {
  const p = useProjection();
  const show = window_(t, 33.2, 35.4);
  if (show <= 0) return null;
  const [x, y] = project(p, P.pyry);
  return (
    <circle cx={x} cy={y} r={60 + 40 * ramp(t, 33.2, 34.2)} fill="rgba(255,201,74,0.10)" stroke={COLORS.gold} strokeWidth={3} strokeDasharray="10 10" opacity={show} />
  );
};

export const Enigma: React.FC = () => {
  const t = useSeconds();
  const frame = useCurrentFrame();
  const cam = cameraAt(CAMERA, t);
  const [sx, sy] = [shake(t, 2.6, 0.35, 14), shake(t, 18.3, 0.4, 18), shake(t, 30.1, 0.6, 16), shake(t, 46.7, 0.8, 30)].reduce(
    (a, b) => [a[0] + b[0], a[1] + b[1]],
    [0, 0],
  );

  // Poland: drawn in at "Three Polish", red when invaded, gold at the end.
  const polandDraw = ramp(t, 4.6, 6.0);
  const polandIn = window_(t, 4.6, 31.2) + window_(t, 45.6, 48.6) + window_(t, 69.6, DURATION + 1);

  return (
    <AbsoluteFill style={{background: COLORS.ocean}}>
      <AbsoluteFill style={{transform: `translate(${sx}px, ${sy}px) scale(1.03)`}}>
        <WorldMap cam={cam} borders={BORDERS}>
          {POLAND && (
            <>
              <Country f={POLAND} draw={polandDraw} fill={0.9} color={COLORS.white} hatch="white" opacity={Math.min(1, polandIn) * (t < 45.6 || t > 49 ? 1 : 0)} />
              <Country f={POLAND} draw={ramp(t, 46.5, 47.2)} fill={1} color={COLORS.red} hatch="red" opacity={window_(t, 46.5, 48.6)} />
            </>
          )}

          {/* 0–4: the Hollywood version — Turing in Britain */}
          <Pin at={P.bletchley} label="Bletchley Park" show={window_(t, -1, 4.4)} color={COLORS.white} />
          <PhotoCard src="enigma/art/turing.jpg" x={330} y={560} w={400} h={500} rotate={-4} show={window_(t, -1, 4.4)} anchor={P.bletchley} name="ALAN TURING" cross={ramp(t, 2.55, 3.1)} />

          {/* 4.6–8: three Polish mathematicians */}
          <Pin at={P.warsaw} label="Warsaw" show={window_(t, 4.8, 13.0)} />
          <PhotoCard src="enigma/art/rejewski.jpg" x={250} y={640} w={250} h={320} rotate={-6} show={ramp(t, 4.76, 5.1) * (1 - ramp(t, 9.4, 9.7))} anchor={P.warsaw} name="REJEWSKI" />
          <PhotoCard src="enigma/art/zygalski.jpg" x={545} y={560} w={250} h={320} rotate={2} show={ramp(t, 5.1, 5.45) * (1 - ramp(t, 9.4, 9.7))} anchor={P.warsaw} name="ZYGALSKI" />
          <PhotoCard src="enigma/art/rozycki.jpg" x={835} y={650} w={250} h={320} rotate={7} show={ramp(t, 5.45, 5.8) * (1 - ramp(t, 9.4, 9.7))} anchor={P.warsaw} name="RÓŻYCKI" />

          {/* 9.7–14.6: Enigma, unbreakable, every army on Earth */}
          <Pin at={P.berlin} label="Berlin" show={window_(t, 9.8, 13.2)} side="left" />
          <PhotoCard src="enigma/art/enigma.jpg" x={540} y={700} w={600} h={460} rotate={-2} show={window_(t, 9.72, 14.6)} anchor={P.berlin} />

          {/* 14.8–21.5: Rejewski breaks it with pure maths */}
          <Pin at={P.warsaw} label="Warsaw" show={window_(t, 15.2, 22.0)} />
          <PhotoCard src="enigma/art/rejewski.jpg" x={300} y={560} w={330} h={420} rotate={-5} show={window_(t, 16.85, 22.0)} anchor={P.warsaw} name="MARIAN REJEWSKI" />
          <PhotoCard src="enigma/art/enigma.jpg" x={780} y={640} w={380} h={300} rotate={6} show={window_(t, 17.6, 18.9)} cross={ramp(t, 18.3, 18.7)} />

          {/* 22–31: Poland reads the traffic; then Germany changes Enigma */}
          <Pin at={P.berlin} label="Berlin" show={window_(t, 22.2, 31.4)} color={t > 26.0 ? COLORS.red : COLORS.white} side="left" pulse={pulseAt(t, 26.0)} />
          <Pin at={P.warsaw} label="Warsaw" show={window_(t, 22.2, 31.4)} />
          <Signal from={P.berlin} to={P.warsaw} t={t} show={window_(t, 23.0, 26.2)} color={COLORS.blue} />
          <Signal from={P.berlin} to={P.warsaw} t={t} show={window_(t, 26.2, 31.4)} color={COLORS.red} speed={0.5} />

          {/* 31.8–35: the forest outside Warsaw */}
          <Pin at={P.warsaw} label="Warsaw" show={window_(t, 32.6, 35.4)} side="left" />
          <PyryRing t={t} />
          <Pin at={P.pyry} label="Pyry Forest" sub="25–26 July 1939 · secret meeting" show={window_(t, 33.3, 35.4)} color={COLORS.gold} pulse={pulseAt(t, 33.4)} />

          {/* 35.5–43: British and French come, Poland hands over everything */}
          <Pin at={P.london} label="London" show={window_(t, 35.8, 43.4)} size={44} />
          <Pin at={P.paris} label="Paris" show={window_(t, 36.3, 43.4)} size={44} />
          <Pin at={P.warsaw} label="Warsaw" show={window_(t, 35.8, 43.4)} side="left" size={44} />
          <Route path={[P.london, P.warsaw]} progress={ramp(t, 36.0, 37.4)} color={COLORS.blue} bend={-0.12} opacity={1 - ramp(t, 38.0, 38.5)} />
          <Route path={[P.paris, P.warsaw]} progress={ramp(t, 36.5, 37.8)} color={COLORS.white} bend={0.1} opacity={1 - ramp(t, 38.0, 38.5)} />
          <Route path={[P.warsaw, P.london]} progress={ramp(t, 38.5, 42.6, (x) => x)} color={COLORS.gold} bend={0.12} opacity={1 - ramp(t, 43.3, 43.8)} />
          <Route path={[P.warsaw, P.paris]} progress={ramp(t, 38.5, 42.6, (x) => x)} color={COLORS.gold} bend={-0.1} opacity={1 - ramp(t, 43.3, 43.8)} />
          <PhotoCard src="enigma/art/enigma.jpg" x={760} y={600} w={330} h={260} rotate={5} show={window_(t, 41.7, 43.5)} glow={COLORS.gold} />

          {/* 43.7–44.6: the British couldn't believe it */}
          <Pin at={P.london} label="London" show={window_(t, 43.8, 45.2)} pulse={pulseAt(t, 44.0)} color={COLORS.blue} />

          {/* 45.4–48: invasion */}
          {t > 46.5 && t < 48.8 && (<>
          <Arrow from={[15.2, 54.2]} to={[18.4, 53.1]} progress={ramp(t, 46.66, 47.6)} />
          <Arrow from={[20.6, 54.6]} to={[20.9, 52.75]} progress={ramp(t, 46.8, 47.7)} />
          <Arrow from={[16.2, 50.6]} to={[19.4, 51.5]} progress={ramp(t, 46.9, 47.8)} />
          <Arrow from={[19.9, 48.9]} to={[20.8, 50.4]} progress={ramp(t, 47.0, 47.9)} />
          </>)}
          <PhotoCard src="enigma/art/invasion.jpg" x={540} y={1360} w={640} h={420} rotate={-3} show={window_(t, 46.9, 48.6)} />

          {/* 48.2–52.4: escape through Romania to France */}
          <Pin at={P.warsaw} label="Warsaw" show={window_(t, 48.4, 52.8)} side="left" size={44} />
          <Pin at={P.bucharest} label="Romania" show={window_(t, 49.5, 52.8)} side="left" size={44} />
          <Pin at={P.paris} label="France" show={window_(t, 50.2, 52.8)} size={44} />
          <Route path={[P.warsaw, P.chernivtsi, P.bucharest, P.paris]} progress={ramp(t, 48.6, 51.6, (x) => x)} bend={0.08} opacity={1 - ramp(t, 52.6, 53.2)} />

          {/* 53–63.5: Bletchley, Turing, the Bombe; Rejewski kept out */}
          <Pin at={P.bletchley} label="Bletchley Park" show={window_(t, 53.4, 63.8)} color={t > 59.5 && t < 60.6 ? COLORS.gold : COLORS.white} pulse={pulseAt(t, 59.6)} />
          <PhotoCard src="enigma/art/bletchley.jpg" x={540} y={1380} w={720} h={430} rotate={2} show={window_(t, 53.6, 56.0)} />
          <PhotoCard src="enigma/art/turing.jpg" x={300} y={600} w={330} h={420} rotate={-5} show={window_(t, 54.0, 63.6)} anchor={P.bletchley} name="ALAN TURING" glow={t > 59.5 ? COLORS.gold : undefined} />
          <PhotoCard src="enigma/art/bombe.jpg" x={790} y={1380} w={460} h={340} rotate={4} show={window_(t, 56.1, 59.2)} />
          <PhotoCard src="enigma/art/rejewski.jpg" x={790} y={1330} w={300} h={380} rotate={6} show={window_(t, 61.1, 63.6)} anchor={P.bletchley} name="REJEWSKI" cross={ramp(t, 62.8, 63.3)} />

          {/* 64–69: he goes home, an office clerk, silent */}
          <Route path={[P.bletchley, P.bydgoszcz]} progress={ramp(t, 64.6, 66.4)} bend={-0.08} opacity={1 - ramp(t, 68.6, 69.4)} />
          <Pin at={P.bydgoszcz} label="Home" show={window_(t, 66.0, 69.4)} side="left" />
          <PhotoCard src="enigma/art/rejewski.jpg" x={540} y={1250} w={360} h={460} rotate={-2} show={window_(t, 65.5, DURATION + 1)} gray={1 - ramp(t, 70.3, 72.4)} anchor={t < 69.4 ? P.bydgoszcz : undefined} name="MARIAN REJEWSKI" glow={t > 70.3 ? COLORS.gold : undefined} />
        </WorldMap>
      </AbsoluteFill>

      {/* Rotor wiring rebuilt "on paper" */}
      <svg width={1080} height={1920} style={{position: 'absolute', inset: 0}}>
        <Wiring x={760} y={1250} show={window_(t, 18.9, 22.0)} progress={ramp(t, 19.0, 21.3, (x) => x)} />
      </svg>

      <Vignette />
      {/* "Silent." — everything drains except Rejewski */}
      <AbsoluteFill style={{background: '#000', opacity: 0.55 * window_(t, 68.6, 70.4, 0.4)}} />

      <BigWord text="NOT" show={window_(t, 2.6, 4.2, 0.08)} y={1360} size={220} color={COLORS.red} />
      <BigWord text="7 YEARS EARLY" show={window_(t, 6.44, 8.0, 0.1)} y={1420} size={96} />
      <BigWord text="1932" show={window_(t, 8.1, 9.6, 0.08)} y={1380} size={220} />
      <BigWord text="UNBREAKABLE?" show={window_(t, 13.6, 14.7, 0.1)} y={1420} size={110} />
      <BigWord text="JULY 1939" show={window_(t, 31.8, 33.2, 0.1)} y={1380} size={150} color={COLORS.gold} />
      <BigWord text="5 WEEKS LATER" show={window_(t, 45.46, 46.6, 0.1)} y={1420} size={110} />
      <BigWord text="SILENT." show={window_(t, 68.8, 69.6, 0.1)} y={760} size={130} />

      <Flash t={t} at={2.6} color={COLORS.red} strength={0.35} />
      <Flash t={t} at={18.3} />
      <Flash t={t} at={46.66} color={COLORS.red} strength={0.5} />
      <Flash t={t} at={63.0} color={COLORS.red} strength={0.3} />

      <Grain frame={frame} />

      <Audio src={staticFile('enigma/vo.wav')} />
      <Audio src={staticFile('enigma/sfx/drone.wav')} volume={(f) => 0.22 * interpolate(f / 30, [0, 1, DURATION - 2, DURATION], [0, 1, 1, 0], {extrapolateRight: 'clamp'})} />
      {WHOOSH.map((s) => (
        <Sequence key={`w${s}`} from={Math.round(s * 30)} durationInFrames={30}>
          <Audio src={staticFile('enigma/sfx/whoosh.wav')} volume={0.32} />
        </Sequence>
      ))}
      {HIT.map((s) => (
        <Sequence key={`h${s}`} from={Math.round(s * 30)} durationInFrames={60}>
          <Audio src={staticFile('enigma/sfx/hit.wav')} volume={0.5} />
        </Sequence>
      ))}
    </AbsoluteFill>
  );
};
